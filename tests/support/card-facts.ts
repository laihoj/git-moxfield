const BY_NAME = new Map(Object.entries(CARD_FACTS).map(([name, facts]) => [name.toLowerCase(), facts]));

/** A card's type line and mana cost by name (case does not matter); `undefined` for a card that is not in the table. */
export function cardFacts(name: string): { typeLine: string; manaCost: string } | undefined {
  const facts = BY_NAME.get(name.toLowerCase());
  return facts === undefined ? undefined : { typeLine: facts[0], manaCost: facts[1] };
}

/**
 * A Moxfield card entry for `name` with its type line and mana cost, plus `extra` fields
 * (quantity, printing).
 * @throws {Error} for a card that is not in the table: add it to {@link CARD_FACTS}.
 */
export function cardWithFacts<T extends object = object>(
  name: string,
  extra?: T,
): { name: string; typeLine: string; manaCost: string } & T {
  const facts = cardFacts(name);
  if (facts === undefined) throw new Error(`Unknown card: ${name}. Add its facts to CARD_FACTS.`);
  return { name, ...facts, ...extra } as { name: string; typeLine: string; manaCost: string } & T;
}
