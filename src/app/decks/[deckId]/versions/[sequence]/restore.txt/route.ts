/**
 * `GET /decks/{deckId}/versions/{n}/restore.txt`: the restore export of a version as a
 * plain-text download (steps, every section, limitations).
 */
import type { NextRequest } from 'next/server';

import type { RestoreDTO } from '@/server/services/types';

import { deckServices, decodeSegment, parseSequence } from '../../../data';

export const dynamic = 'force-dynamic';

/** ASCII-only, filesystem-safe slug for the download name. */
function fileSlug(name: string): string {
  const slug = name
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return slug === '' ? 'deck' : slug;
}

function restoreText({ deck, version, export: restore }: RestoreDTO): string {
  const lines: string[] = [
    `${deck.name} — v${version.sequence}: ${version.message}`,
    `Restore text generated by git-moxfield. Paste each section into Moxfield's Bulk Edit.`,
    '',
    'STEPS',
    ...restore.instructions.map((step, index) => `${index + 1}. ${step}`),
    '',
  ];
  for (const section of restore.sections) {
    lines.push(
      `=== ${section.label} (${section.cardCount} ${section.cardCount === 1 ? 'card' : 'cards'}) ===`,
    );
    lines.push(`Paste into: ${section.target}`);
    lines.push(section.text === '' ? '(empty: clear this tab)' : section.text.trimEnd());
    lines.push('');
  }
  if (restore.primer !== null) {
    lines.push('=== Primer ===', `Paste into: ${restore.primer.target}`);
    lines.push(restore.primer.text === '' ? '(no primer: clear the primer)' : restore.primer.text.trimEnd());
    lines.push('');
  }
  if (restore.combined !== null) {
    lines.push(
      '=== Create a new deck instead (combined list) ===',
      restore.combined.note,
      restore.combined.text.trimEnd(),
      '',
    );
  }
  if (restore.limitations.length > 0) {
    lines.push('LIMITATIONS', ...restore.limitations.map((limitation) => `- ${limitation}`), '');
  }
  return lines.join('\n');
}

export async function GET(
  _request: NextRequest,
  { params }: RouteContext<'/decks/[deckId]/versions/[sequence]/restore.txt'>,
): Promise<Response> {
  const { deckId, sequence: rawSequence } = await params;
  const sequence = parseSequence(rawSequence);
  const id = decodeSegment(deckId);
  const restore = sequence === null ? null : await (await deckServices(id)).restoreExport(id, sequence);
  if (restore === null) {
    return new Response('Version not found.\n', {
      status: 404,
      headers: { 'content-type': 'text/plain; charset=utf-8' },
    });
  }
  const filename = `${fileSlug(restore.deck.name)}-v${restore.version.sequence}-restore.txt`;
  return new Response(restoreText(restore), {
    headers: {
      'content-type': 'text/plain; charset=utf-8',
      'content-disposition': `attachment; filename="${filename}"`,
      'cache-control': 'no-store',
    },
  });
}
