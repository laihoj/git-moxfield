/**
 * The `restore.txt` download of a version: its restore export as plain text (steps, every
 * section, limitations). Shared by the owner's route (`/decks/{id}/versions/{n}/restore.txt`)
 * and the shared deck's (`/s/{token}/versions/{n}/restore.txt`), so both read the same.
 */
import { pluralize } from '@/core/text';
import type { RestoreExport } from '@/integrations/deck-source';
import type { VersionRefDTO } from '@/server/services/types';

/** What a download needs: the owner's `RestoreDTO` and the viewer's `SharedRestoreDTO` both fit. */
export interface RestoreDownload {
  deck: { name: string };
  version: Pick<VersionRefDTO, 'sequence' | 'message'>;
  export: RestoreExport;
}

/** The download's file name: `<deck-slug>-v<n>-restore.txt` (ASCII only). */
export function restoreFileName({ deck, version }: RestoreDownload): string {
  return `${fileSlug(deck.name)}-v${version.sequence}-restore.txt`;
}

/**
 * The response of a download: the text as an attachment named by {@link restoreFileName}.
 * `headers` are added (the owner's route says `no-store`, the shared one its private headers).
 */
export function restoreDownloadResponse(download: RestoreDownload, headers?: HeadersInit): Response {
  return new Response(restoreText(download), {
    headers: {
      'content-type': 'text/plain; charset=utf-8',
      'content-disposition': `attachment; filename="${restoreFileName(download)}"`,
      ...Object.fromEntries(new Headers(headers)),
    },
  });
}

/** The download's text. */
export function restoreText({ deck, version, export: restore }: RestoreDownload): string {
  const lines: string[] = [
    `${deck.name} — v${version.sequence}: ${version.message}`,
    `Restore text generated by git-moxfield. Paste each section into Moxfield's Bulk Edit.`,
    '',
    'STEPS',
    ...restore.instructions.map((step, index) => `${index + 1}. ${step}`),
    '',
  ];
  for (const section of restore.sections) {
    lines.push(`=== ${section.label} (${pluralize(section.cardCount, 'card')}) ===`);
    lines.push(`Paste into: ${section.target}`);
    lines.push(section.text === '' ? '(empty: clear this tab)' : section.text.trimEnd());
    lines.push('');
  }
  if (restore.primer !== null) {
    lines.push('=== Primer ===', `Paste into: ${restore.primer.target}`);
    lines.push(restore.primer.text === '' ? '(no primer: clear the primer)' : restore.primer.text.trimEnd());
    lines.push('');
  }
  if (restore.combined !== null) {
    lines.push(
      '=== Create a new deck instead (combined list) ===',
      restore.combined.note,
      restore.combined.text.trimEnd(),
      '',
    );
  }
  if (restore.limitations.length > 0) {
    lines.push('LIMITATIONS', ...restore.limitations.map((limitation) => `- ${limitation}`), '');
  }
  return lines.join('\n');
}

/** ASCII-only, filesystem-safe slug for the download name. */
function fileSlug(name: string): string {
  const slug = name
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return slug === '' ? 'deck' : slug;
}
