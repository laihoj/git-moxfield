import { describe, expect, it } from 'vitest';

import type { RestoreExport } from '@/integrations/deck-source';

import { restoreFileName, restoreText, type RestoreDownload } from './restore-download';

const EXPORT: RestoreExport = {
  source: 'moxfield',
  instructions: ['Open the deck on Moxfield.', 'Open Bulk Edit.'],
  sections: [
    {
      zone: 'mainboard',
      label: 'Mainboard',
      target: 'Bulk Edit › Main Deck',
      text: '1 Sol Ring\n',
      cardCount: 1,
    },
    { zone: 'sideboard', label: 'Sideboard', target: 'Bulk Edit › Sideboard', text: '', cardCount: 0 },
  ],
  primer: { target: 'Deck page › Primer › Edit', text: '# Plan\n' },
  combined: null,
  limitations: ['Card tags are not restored.'],
};

function download(name: string, overrides: Partial<RestoreExport> = {}): RestoreDownload {
  return {
    deck: { name },
    version: { sequence: 3, message: 'Cut Dress Down' },
    export: { ...EXPORT, ...overrides },
  };
}

describe('restoreText', () => {
  it('lists the steps, every section, the primer and the limitations', () => {
    expect(restoreText(download('Blue Farm'))).toBe(
      [
        'Blue Farm — v3: Cut Dress Down',
        "Restore text generated by git-moxfield. Paste each section into Moxfield's Bulk Edit.",
        '',
        'STEPS',
        '1. Open the deck on Moxfield.',
        '2. Open Bulk Edit.',
        '',
        '=== Mainboard (1 card) ===',
        'Paste into: Bulk Edit › Main Deck',
        '1 Sol Ring',
        '',
        '=== Sideboard (0 cards) ===',
        'Paste into: Bulk Edit › Sideboard',
        '(empty: clear this tab)',
        '',
        '=== Primer ===',
        'Paste into: Deck page › Primer › Edit',
        '# Plan',
        '',
        'LIMITATIONS',
        '- Card tags are not restored.',
        '',
      ].join('\n'),
    );
  });

  it('says to clear an empty primer and leaves out what is missing', () => {
    const text = restoreText(
      download('Blue Farm', { primer: { target: 'Primer', text: '' }, limitations: [] }),
    );
    expect(text).toContain('(no primer: clear the primer)');
    expect(text).not.toContain('LIMITATIONS');
    expect(restoreText(download('Blue Farm', { primer: null }))).not.toContain('=== Primer ===');
  });
});

describe('restoreFileName', () => {
  it.each([
    ['Blue Farm', 'blue-farm-v3-restore.txt'],
    ['Tymna & Kraum: Æther', 'tymna-kraum-ther-v3-restore.txt'],
    ['Lórien', 'lorien-v3-restore.txt'],
    ['"quoted"/..\\path', 'quoted-path-v3-restore.txt'],
    ['名前', 'deck-v3-restore.txt'],
  ])('names %j as %j', (name, file) => {
    expect(restoreFileName(download(name))).toBe(file);
  });
});
